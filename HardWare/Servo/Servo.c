#include "stm32l4xx.h"                  // Device header
#include "Servo.h"
#include "tim.h"

/*==============================================================================
 * 舵机驱动（道闸的两根杆，两个 MG996R）
 *----------------------------------------------------------------------------
 * 一、舵机是怎么被控制的
 *    MG996R 只认信号线上的脉宽：每 20ms（50Hz）来一个高电平脉冲，
 *    0.5ms -> 0 度，1.5ms -> 90 度，2.5ms -> 180 度，中间线性对应。
 *    脉冲一停，舵机就没有保持力，杆会自己垂下来。
 *
 * 二、两个舵机接在哪
 *    舵机1（上杆）信号 = PA11，走 TIM1_CH4
 *    舵机2（下杆）信号 = PA15，走 TIM2_CH1
 *    （出处：厂商例程 Resource/Hardware/P0080/p0080.c，仓库闸机场景实训）
 *
 * 三、为什么 TIM1 现在是 50Hz
 *    风扇原来用 TIM1_CH1 做 2kHz 调速，和舵机1 抢同一个定时器的 PSC/ARR，
 *    只能二选一。现在风扇改成纯开关（占空比 0% 或 100%），
 *    50Hz 下这两个状态照样成立，于是 TIM1 整条降到 50Hz，
 *    舵机1 直接用硬件 PWM，和厂商例程的配置完全一致：
 *        舵机1 = TIM1_CH4，舵机2 = TIM2_CH1，都是 PSC=799 / ARR=1999。
 *    两个舵机都不占 CPU，也不再需要中断。
 *============================================================================*/

/*----------------------------------------------------------------------------
 * 行程校准参数
 *--------------------------------------------------------------------------
 * 理论 0.5~2.5ms 对应 0~180 度，但个体之间有 5~15 度公差，
 * 这台箱子上两个舵机还是不同厂牌（TowerPro 和 Power HD），偏差更明显。
 * 所以两组参数分开写，哪根杆角度不对就调哪一组。
 *
 * 单位：TIM1 / TIM2 的计数时钟都是 100kHz，1 个计数 = 10us，
 *       50 = 500us（0 度），150 = 1500us（90 度），250 = 2500us（180 度）。
 * 调法：杆抬得不够高就加大 MAX，压得不够平就减小 MIN，一次改 10~20 试。 */
#define S1_MIN_CCR    50        /* 舵机1：0 度 */
#define S1_MAX_CCR    250       /* 舵机1：180 度 */
#define S2_MIN_CCR    50        /* 舵机2：0 度 */
#define S2_MAX_CCR    250       /* 舵机2：180 度 */

/*----------------------------------------------------------------------------
 * 开闸 / 关闸对应的角度
 *--------------------------------------------------------------------------
 * 关闸：两根杆都落到 90 度（中位），杆贴平挡住通道。
 * 开闸：一根 180、一根 0——两个舵机装在两根杆输出轴的对侧，机械上镜像，
 *       要让两根杆朝同一边抬起，电角度就必须相反。
 *       厂商例程开闸给的 250 / 50，正是这个关系。
 * 现场如果一根抬一根压，把那一根的 OPEN 和 CLOSE 对调。 */
#define GATE_OPEN_S1    180
#define GATE_CLOSE_S1   90
#define GATE_OPEN_S2    0
#define GATE_CLOSE_S2   90

/*----------------------------------------------------------------------------
 * 名    称：Servo_Init
 * 功    能：启动两路舵机 PWM，并先把闸关上
 * 说    明：TIM1/TIM2 的 PSC、ARR、通道模式已经在 tim.c 里配好
 *           （都是 50Hz，CCR 单位 10us），这里只负责启动通道。
 *           硬件 PWM 一旦启动就一直输出，不需要主循环再管。
 * 调用方法：main.c 初始化段
 *--------------------------------------------------------------------------*/
void Servo_Init(void)
{
    HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_4);   /* 舵机1：PA11 */
    HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_1);   /* 舵机2：PA15 */

    Gate_Close();       /* 上电先摆成关闸姿态，和 g_gate_open = 0 对齐 */
}

/*----------------------------------------------------------------------------
 * 名    称：Servo_SetAngle1
 * 功    能：设置舵机1（上杆，PA11）的角度
 * 参数说明：deg —— 0~180，超出会被夹到 180
 * 说    明：角度线性映射成 CCR 写进 TIM1_CH4，纯硬件输出。
 * 调用方法：Gate_Open / Gate_Close 内部调用，也可以单独调来微调
 *--------------------------------------------------------------------------*/
void Servo_SetAngle1(uint8_t deg)
{
    if (deg > 180) deg = 180;
    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_4,
                          S1_MIN_CCR + (uint16_t)deg * (S1_MAX_CCR - S1_MIN_CCR) / 180);
}

/*----------------------------------------------------------------------------
 * 名    称：Servo_SetAngle2
 * 功    能：设置舵机2（下杆，PA15）的角度
 * 参数说明：deg —— 0~180
 * 说    明：算法和舵机1 一样，只是换到 TIM2_CH1。
 * 调用方法：Gate_Open / Gate_Close 内部调用
 *--------------------------------------------------------------------------*/
void Servo_SetAngle2(uint8_t deg)
{
    if (deg > 180) deg = 180;
    __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1,
                          S2_MIN_CCR + (uint16_t)deg * (S2_MAX_CCR - S2_MIN_CCR) / 180);
}

/*----------------------------------------------------------------------------
 * 名    称：Gate_Open
 * 功    能：开闸，两根杆同时抬起
 * 说    明：中间 30ms 是错开启动。MG996R 堵转电流单个能到 2A，
 *           两个同时从静止启动容易把 5V 拉低，轻则复位、重则舵机乱走。
 *           30ms 对观感没影响，电源压力小一半。
 * 调用方法：main.c 的 KEY3、PIR、烟感三处
 *--------------------------------------------------------------------------*/
void Gate_Open(void)
{
    Servo_SetAngle1(GATE_OPEN_S1);
    HAL_Delay(30);
    Servo_SetAngle2(GATE_OPEN_S2);
}

/*----------------------------------------------------------------------------
 * 名    称：Gate_Close
 * 功    能：关闸，两根杆收回 90 度
 * 说    明：关闸时两根杆往中间收，注意机械上别让它们互相撞到；
 *           如果撞了，把 GATE_CLOSE_S1 / S2 各往两边调 5~10 度。
 * 调用方法：Servo_Init 内部、main.c 的 KEY3 和 PIR 超时分支
 *--------------------------------------------------------------------------*/
void Gate_Close(void)
{
    Servo_SetAngle1(GATE_CLOSE_S1);
    HAL_Delay(30);
    Servo_SetAngle2(GATE_CLOSE_S2);
}
